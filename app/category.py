_STAR = re.compile(r"\*([^*]+)\*")


def _match_keywords(text: str) -> Optional[str]:
    for cat, kws in _RULES:
        for kw in kws:
            if kw in text:
                return cat
    return None


def classify(name: Optional[str], tax_code: Optional[str] = None,
             seller_name: Optional[str] = None) -> str:
    """把一条发票明细归到费用类别。"""
    raw = (name or "").strip()
    text = raw

    # 1) 星号内的税收分类大类：「*餐饮服务*餐饮服务」→「餐饮服务」
    m = _STAR.search(raw)
    if m:
        hit = _match_keywords(m.group(1) + raw)
        if hit:
            return hit

    # 2) 税收分类编码前 6 位
    if tax_code:
        code = re.sub(r"\D", "", str(tax_code))
        for prefix, cat in _CODE_PREFIX_RULES:
            if code.startswith(prefix):
                return cat

    # 3) 明细名称关键词
    hit = _match_keywords(text)
    if hit:
        return hit

    # 4) 销方名称兜底（如「XX加油站」「XX酒店」）
    if seller_name:
        hit = _match_keywords(str(seller_name))
        if hit:
            return hit

    return "其他"


def classify_invoice(items: List["object"]) -> Tuple[Optional[str], List[str]]:
    """按明细行金额加权，给出整张发票的主类别与全部类别。

    主类别 = 金额最大的明细行类别；类别列表按金额从大到小去重。
    """
    from decimal import Decimal
    weights: dict = {}
    for it in items or []:
        cat = getattr(it, "category", None) or "其他"
        amt = getattr(it, "amount", None) or Decimal("0")
        try:
            amt = Decimal(str(amt))
        except Exception:
            amt = Decimal("0")
        weights[cat] = weights.get(cat, Decimal("0")) + amt

    if not weights:
        return None, []
    ordered = sorted(weights.items(), key=lambda kv: (-kv[1], kv[0]))
    main = ordered[0][0]
    return main, [c for c, _ in ordered]


def category_order(cat: Optional[str]) -> int:
    """报表排序权重。"""
    try:
        return CATEGORIES.index(cat or "其他")
    except ValueError:
        return len(CATEGORIES)
